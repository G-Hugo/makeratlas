function restore(text) {
  let out = text;
  for (const [from, to] of words) {
    const re = new RegExp(`\\b${from}\\b`, "gi");
    out = out.replace(re, (m) => {
      if (m === m.toUpperCase()) return to.toUpperCase();
      if (m[0] === m[0].toUpperCase()) return to[0].toUpperCase() + to.slice(1);
      return to;
    });
  }
  return out;
}

