function perf(o = {}) {
  return {
    precision: o.precision ?? "0.01 mm",
    engraveExample: {
      description: "Filled photo or logo on birch plywood",
      size: "10 × 10 cm (4 × 4 in)",
      time: o.engrave ?? "~10–15 min",
    },
    cutExample: {
      description: o.cut === "Not a cutter" ? "Laser cutting" : "Simple square cut-out from 3 mm basswood",
      size: o.cut === "Not a cutter" ? "—" : "10 × 10 cm (4 × 4 in)",
      time: o.cut ?? "~5–8 min",
    },
    technical: {
      spotSize: o.spot ?? "~0.08 mm spot",
      maxSpeed: o.max ?? "300 mm/s",
      avgEngraveSpeed: o.engraveSp ?? "60–150 mm/s fill",
      avgCutSpeed: o.cutSp ?? "4–10 mm/s on 3 mm wood",
    },
  };
}

