function perf({
  precision = "0.01 mm",
  spot = "~0.08 mm spot",
  max = "300 mm/s",
  engrave = "~10–15 min",
  cut = "~5–8 min",
  engraveSp,
  cutSp,
} = {}) {
  return {
    precision,
    engraveExample: {
      description: "Filled photo or logo on birch plywood",
      size: "10 × 10 cm (4 × 4 in)",
      time: engrave,
    },
    cutExample: {
      description: cut === "Not a cutter" ? "Laser cutting" : "Simple square cut-out from 3 mm basswood",
      size: cut === "Not a cutter" ? "—" : "10 × 10 cm (4 × 4 in)",
      time: cut,
    },
    technical: {
      spotSize: spot,
      maxSpeed: max,
      avgEngraveSpeed: engraveSp ?? "60–150 mm/s fill",
      avgCutSpeed: cutSp ?? "4–10 mm/s on 3 mm wood",
    },
  };
}

function m(def) {
  const slug = def.slug;
  return {
    id: slug,
    slug,
    name: def.name,
    brand: def.brand,
    category: "laser-engraver",
    laserType: def.laserType,
    tagline: def.tagline,
    tldr: def.tldr,
    mainObjective: def.mainObjective,
    bestFor: def.bestFor,
    priceRange: def.priceRange,
    specs: {
      power: def.power,
      workArea: def.workArea,
      software: def.software ?? ["LightBurn", "LaserGRBL"],
      connectivity: def.connectivity ?? ["USB", "Wi-Fi"],
      performance: perf(def.perf ?? {}),
    },
    materials: def.materials,
    pros: def.pros,
    cons: def.cons,
    beginnerNotes: def.beginnerNotes,
    proTips: def.proTips,
    primaryUse: def.primaryUse,
    rating: def.rating ?? {
      overall: 8,
      value: 8,
      easeOfUse: 8,
      capability: 8,
      buildQuality: 7.8,
    },
    similarModels: def.similarModels ?? [],
    status: "published",
    lastUpdated: "2026-06-01",
    image: `/machines/${slug}.svg`,
    ...(def.modelLine ? { modelLine: def.modelLine } : {}),
    ...(def.powerRating ? { powerRating: def.powerRating } : {}),
    ...(def.catalogPrimary ? { catalogPrimary: true } : {}),
    ...(def.catalogHidden ? { catalogHidden: true } : {}),
    ...(def.moduleSystem ? { moduleSystem: def.moduleSystem } : {}),
    ...(def.laserCapabilities ? { laserCapabilities: def.laserCapabilities } : {}),
    ...(def.capabilityTags ? { capabilityTags: def.capabilityTags } : {}),
    ...(def.releaseDate ? { releaseDate: def.releaseDate } : {}),
  };
}

