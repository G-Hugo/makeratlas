function perf(o = {}) {
  return {
    precision: o.precision ?? "0.01 mm",
    engraveExample: {
      description: "Filled photo or logo on birch plywood",
      size: "10 × 10 cm (4 × 4 in)",
      time: o.engrave ?? "~10–15 min",
    },
    cutExample: {
      description: o.cut === "Not a cutter" ? "Laser cutting" : "Simple square cut-out from 3 mm basswood",
      size: o.cut === "Not a cutter" ? "—" : "10 × 10 cm (4 × 4 in)",
      time: o.cut ?? "~5–8 min",
    },
    technical: {
      spotSize: o.spot ?? "~0.08 mm spot",
      maxSpeed: o.max ?? "300 mm/s",
      avgEngraveSpeed: o.engraveSp ?? "60–150 mm/s fill",
      avgCutSpeed: o.cutSp ?? "4–10 mm/s on 3 mm wood",
    },
  };
}

function m(def) {
  const slug = def.slug;
  return {
    id: slug,
    slug,
    name: def.name,
    brand: def.brand,
    category: "laser-engraver",
    laserType: def.laserType,
    tagline: def.tagline,
    tldr: def.tldr,
    mainObjective: def.mainObjective,
    bestFor: def.bestFor,
    priceRange: def.priceRange,
    specs: {
      power: def.power,
      workArea: def.workArea,
      software: def.software ?? ["LightBurn", "LaserGRBL"],
      connectivity: def.connectivity ?? ["USB", "Wi-Fi"],
      performance: perf(def.perf ?? {}),
    },
    materials: def.materials,
    pros: def.pros,
    cons: def.cons,
    beginnerNotes: def.beginnerNotes,
    proTips: def.proTips,
    primaryUse: def.primaryUse,
    rating: def.rating ?? { overall: 7.8, value: 8, easeOfUse: 8, capability: 7.5, buildQuality: 7.5 },
    similarModels: def.similarModels ?? [],
    status: "published",
    lastUpdated: "2026-06-01",
    image: `/machines/${slug}.svg`,
    ...(def.modelLine && { modelLine: def.modelLine }),
    ...(def.powerRating && { powerRating: def.powerRating }),
    ...(def.catalogPrimary && { catalogPrimary: true }),
    ...(def.catalogHidden && { catalogHidden: true }),
    ...(def.laserCapabilities && { laserCapabilities: def.laserCapabilities }),
    ...(def.capabilityTags && { capabilityTags: def.capabilityTags }),
    ...(def.releaseDate && { releaseDate: def.releaseDate }),
    ...(def.marketAvailability && { marketAvailability: def.marketAvailability }),
    ...(def.marketAvailabilityNote && { marketAvailabilityNote: def.marketAvailabilityNote }),
  };
}

